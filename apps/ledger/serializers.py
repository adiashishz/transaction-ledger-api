import re
from collections.abc import Mapping
from decimal import Decimal

from rest_framework import serializers

from apps.ledger.models import Account, Transaction, TransactionType
from apps.ledger.pagination import DEFAULT_PAGE_SIZE, MAX_PAGE_SIZE


class StrictCharField(serializers.CharField):
    """CharField that rejects non-strings instead of silently turning `123` into `"123"`."""

    default_error_messages = {"not_a_string": "Must be a string."}

    def to_internal_value(self, data):
        if not isinstance(data, str):
            self.fail("not_a_string")
        return super().to_internal_value(data)


class AmountField(serializers.DecimalField):
    """A positive money amount with at most 2 decimal places, sent as a JSON number or a plain decimal string.

    Strings must look like `100` or `100.50`. Python's Decimal() would also accept forms such as `1e2`,
    `+5`, ` 7 `, `1_000` or non-ASCII digits; none of those are sensible ways to write money, so they
    are rejected. Precision, size and sign are left to DecimalField so their messages stay specific.
    """

    PLAIN_DECIMAL = re.compile(r"-?[0-9]+(\.[0-9]+)?")
    default_error_messages = {
        "format": "Amount must be a plain decimal like 100 or 100.50.",
        "min_value": "Amount must be greater than 0.",
    }

    def __init__(self, **kwargs):
        # 12 digits caps a single amount at 9,999,999,999.99, far below the balance column's limit.
        super().__init__(max_digits=12, decimal_places=2, min_value=Decimal("0.01"), **kwargs)

    def to_internal_value(self, data):
        if isinstance(data, str) and not self.PLAIN_DECIMAL.fullmatch(data):
            self.fail("format")
        return super().to_internal_value(data)


class StrictSerializer(serializers.Serializer):
    """Rejects fields the endpoint does not accept instead of silently ignoring them."""

    unknown_field_messages = {}

    def to_internal_value(self, data):
        errors = {}
        if isinstance(data, Mapping):
            errors = {
                field: [self.unknown_field_messages.get(field, "This field is not allowed.")]
                for field in data
                if field not in self.fields
            }
        try:
            value = super().to_internal_value(data)
        except serializers.ValidationError as exc:
            raise serializers.ValidationError({**exc.detail, **errors})
        if errors:
            raise serializers.ValidationError(errors)
        return value


class AccountCreateSerializer(StrictSerializer):
    unknown_field_messages = {
        "balance": "balance cannot be set; new accounts always start at 0.",
        "id": "id is generated by the server.",
        "created_at": "created_at is generated by the server.",
    }

    name = StrictCharField(max_length=255)


class AccountSerializer(serializers.ModelSerializer):
    class Meta:
        model = Account
        fields = ["id", "name", "balance", "created_at"]


class BalanceSerializer(serializers.ModelSerializer):
    account_id = serializers.UUIDField(source="id", read_only=True)

    class Meta:
        model = Account
        fields = ["account_id", "balance"]


class TransactionCreateSerializer(StrictSerializer):
    unknown_field_messages = {
        "account_id": "account_id is taken from the URL.",
        "id": "id is generated by the server.",
        "created_at": "created_at is generated by the server.",
    }

    type = serializers.ChoiceField(choices=TransactionType.choices)
    amount = AmountField()
    reference_id = StrictCharField(max_length=100)
    description = StrictCharField(max_length=255, required=False, allow_blank=True, default="")


class TransactionSerializer(serializers.ModelSerializer):
    account_id = serializers.UUIDField(read_only=True)

    class Meta:
        model = Transaction
        fields = ["id", "account_id", "type", "amount", "description", "reference_id", "created_at"]


class PageQuerySerializer(serializers.Serializer):
    page = serializers.IntegerField(min_value=1, default=1)
    limit = serializers.IntegerField(min_value=1, max_value=MAX_PAGE_SIZE, default=DEFAULT_PAGE_SIZE)


class HistoryQuerySerializer(PageQuerySerializer):
    type = serializers.ChoiceField(
        choices=TransactionType.choices, required=False, help_text="Omit to return both credits and debits."
    )


class PaginationSerializer(serializers.Serializer):
    page = serializers.IntegerField()
    limit = serializers.IntegerField()
    total_records = serializers.IntegerField()
    total_pages = serializers.IntegerField()


class AccountPageSerializer(serializers.Serializer):
    data = AccountSerializer(many=True)
    pagination = PaginationSerializer()


class TransactionPageSerializer(serializers.Serializer):
    data = TransactionSerializer(many=True)
    pagination = PaginationSerializer()


class ErrorDetailSerializer(serializers.Serializer):
    code = serializers.CharField()
    message = serializers.CharField()
    details = serializers.DictField()


class ErrorResponseSerializer(serializers.Serializer):
    """Documents the shared error body; responses are built by `exceptions.exception_handler`."""

    error = ErrorDetailSerializer()
